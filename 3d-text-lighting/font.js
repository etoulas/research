/**
 * Flatten one glyph into polyline *chains*: { pts: [[x,y], ...], closed }.
 * Arcs stay a single chain so the extruder can miter the joints instead of
 * butting square caps together (which spikes on tight curves).
 */
function glyphChains(ch) {
  const g = FONT[ch] || FONT[ch.toUpperCase()];
  if (!g) return null;
  const chains = [];
  for (const s of g.strokes) {
    if (s[0] === 'L') {
      chains.push({ pts: [[s[1], s[2]], [s[3], s[4]]], closed: false });
    } else {
      const [, cx, cy, rx, ry, d0, d1] = s;
      const sweep = d1 - d0;
      const closed = Math.abs(sweep) >= 359.9;
      const steps = Math.max(4, Math.ceil(Math.abs(sweep) / 12));
      const pts = [];
      for (let i = 0; i <= steps; i++) {
        if (closed && i === steps) break;   // don't repeat the seam point
        const t = ((d0 + (sweep * i) / steps) * Math.PI) / 180;
        pts.push([cx + rx * Math.cos(t), cy + ry * Math.sin(t)]);
      }
      chains.push({ pts, closed });
    }
  }
  return { adv: g.adv, chains };
}
